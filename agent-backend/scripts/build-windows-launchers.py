#!/usr/bin/env python3
"""生成四个可单独复制的 BAT；源码留在 source，Windows 无需另外上传 PS1。"""
import argparse
import base64
import hashlib
import io
from pathlib import Path
import textwrap
import zipfile

WINDOWS = Path(__file__).resolve().parents[1] / "deployment/windows"
SOURCE_FILES = ("backend.ps1", "backend-core.ps1", "backend-download.ps1", "signal-stop.ps1",
                "backend-settings.example.json", "backend.env.example", "logback-windows.xml")
ACTIONS = {"update-and-start.bat": "Update", "start-backend.bat": "Start",
           "stop-backend.bat": "Stop", "view-logs.bat": "Logs"}


def embedded_bundle(source):
    """固定 ZIP 顺序和时间戳，使交付脚本可重复生成并检查是否同步。"""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name in SOURCE_FILES:
            text = (source / name).read_text(encoding="utf-8-sig")
            if name.endswith(".ps1"):
                payload = b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8")
            else:
                payload = text.encode("utf-8")
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    return buffer.getvalue()


def generate(source):
    bundle = embedded_bundle(source)
    digest = hashlib.sha256(bundle).hexdigest()
    bootstrap = (source / "bootstrap.ps1").read_text(encoding="utf-8-sig").replace("__BUNDLE_SHA__", digest)
    bootstrap = "\n".join(line for line in bootstrap.splitlines() if not line.lstrip().startswith("#"))
    encoded = base64.b64encode(bootstrap.encode("utf-16le")).decode("ascii")
    command = "powershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -EncodedCommand " + encoded
    # Windows cmd 的单行上限是 8191；留出调用环境开销。
    if len(command) > 8000:
        raise ValueError("启动引导超过 Windows 命令行长度限制")
    payload = "\r\n".join(textwrap.wrap(base64.b64encode(bundle).decode("ascii"), 120))
    result = {}
    for name, action in ACTIONS.items():
        header = ["@echo off", "rem Generated by build-windows-launchers.py; copy this BAT alone.",
                  "setlocal DisableDelayedExpansion", "chcp 65001 >nul",
                  'set "BUTVAN_LAUNCHER_FILE=%~f0"', f'set "BUTVAN_LAUNCHER_ACTION={action}"', command,
                  'set "BACKEND_RESULT=%ERRORLEVEL%"', "pause", "exit /b %BACKEND_RESULT%",
                  ":__BUTVAN_PAYLOAD__"]
        result[name] = ("\r\n".join(header) + "\r\n" + payload + "\r\n").encode("ascii")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只检查 BAT 与源码是否同步")
    args = parser.parse_args()
    for name, content in generate(WINDOWS / "source").items():
        path = WINDOWS / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit(f"BAT 未同步，请运行生成脚本：{name}")
        else:
            path.write_bytes(content)
    print("Windows BAT 已同步" if not args.check else "Windows BAT 同步检查通过")


if __name__ == "__main__":
    main()
